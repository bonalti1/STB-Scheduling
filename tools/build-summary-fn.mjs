#!/usr/bin/env node
// Regenerates supabase/functions/stb-summary/phase-tasks.js from the master checklist
// in index.html, so the read-only summary always uses the same phases and tasks as the board.
// Run after any change to PHASE_TASKS:   node tools/build-summary-fn.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');
const m = html.match(/^var PHASE_TASKS = (\{[\s\S]*?^\});/m);
if (!m) { console.error('PHASE_TASKS not found in index.html'); process.exit(1); }
const PHASE_TASKS = new Function('return (' + m[1] + ')')();
const phases = html.match(/^var PHASES = (\[.*?\]);/m);
const PHASES = phases ? new Function('return ' + phases[1])() : Object.keys(PHASE_TASKS);

const out = `// GENERATED by tools/build-summary-fn.mjs from index.html — do not edit by hand.
export const PHASES = ${JSON.stringify(PHASES)};
export const PHASE_TASKS = ${JSON.stringify(PHASE_TASKS, null, 2)};
`;
writeFileSync(join(root, 'supabase/functions/stb-summary/phase-tasks.js'), out);
console.log('phase-tasks.js written:', PHASES.map(p => p + ' ' + PHASE_TASKS[p].length).join(', '));
